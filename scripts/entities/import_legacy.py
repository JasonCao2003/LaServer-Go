"""Extract declarations only; never import or execute the legacy application."""
import argparse
import ast
import json
import re
import sqlite3
from pathlib import Path


def go_name(name):
    initialisms = {'id': 'ID', 'ip': 'IP', 'url': 'URL', 'os': 'OS', 'iap': 'IAP'}
    return ''.join(initialisms.get(p, p[:1].upper() + p[1:]) for p in name.split('_'))


def snake(name):
    return re.sub(r'((?<=[a-z0-9])[A-Z]|(?!^)[A-Z](?=[a-z]))', r'_\1', name).lower()


def extract(source):
    path = source / 'services/game-api/infrastructure/database/models.py'
    tree = ast.parse(path.read_text(encoding='utf-8-sig'))
    tables = []
    for cls in tree.body:
        if not isinstance(cls, ast.ClassDef) or not any(ast.unparse(b) == 'db.Model' for b in cls.bases):
            continue
        table = {'entity': cls.name, 'table': snake(cls.name), 'source': str(path.relative_to(source)).replace('\\', '/'), 'line': cls.lineno, 'columns': [], 'constraints': []}
        for node in cls.body:
            if not isinstance(node, ast.Assign) or not isinstance(node.targets[0], ast.Name):
                continue
            name = node.targets[0].id
            if name == '__tablename__':
                table['table'] = ast.literal_eval(node.value)
            if name == '__table_args__':
                table['constraints'].append(ast.unparse(node.value))
            value = node.value
            if not isinstance(value, ast.Call) or ast.unparse(value.func) != 'db.Column':
                continue
            kw = {k.arg: k.value for k in value.keywords}
            primary = ast.literal_eval(kw['primary_key']) if 'primary_key' in kw else False
            nullable = ast.literal_eval(kw['nullable']) if 'nullable' in kw else not primary
            typ = value.args[0]
            base = ast.unparse(typ.func if isinstance(typ, ast.Call) else typ).split('.')[-1]
            mapping = {'String': 'string', 'Text': 'string', 'Integer': 'int64', 'BigInteger': 'int64', 'Boolean': 'bool', 'Float': 'float64', 'DateTime': 'time.Time', 'FlexibleDateTime': 'time.Time'}
            if base not in mapping:
                raise ValueError(f'Unsupported type: {base}')
            table['columns'].append({'column': name, 'go_field': go_name(name), 'go_type': ('*' if nullable else '') + mapping[base], 'nullable': nullable, 'primary_key': primary, 'declaration': ast.unparse(value), 'line': node.lineno})
        tables.append(table)
    known = {t['table'] for t in tables}
    # Execute only literal CREATE TABLE statements against an ephemeral memory DB.
    # No application code or INSERT/UPDATE statement is executed.
    with sqlite3.connect(':memory:') as db:
        for path in sorted((source / 'services/game-api').rglob('*.py')):
            for node in ast.walk(ast.parse(path.read_text(encoding='utf-8-sig'))):
                if not isinstance(node, ast.Constant) or not isinstance(node.value, str):
                    continue
                sql = node.value.strip()
                match = re.match(r'CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)\s*\(', sql, re.I)
                if not match or match[1] in known:
                    continue
                db.execute(sql)
                name = match[1]
                table = {'entity': go_name(name), 'table': name, 'source': str(path.relative_to(source)).replace('\\', '/'), 'line': node.lineno, 'columns': [], 'constraints': [sql]}
                for _, col, typ, notnull, default, pk in db.execute(f'PRAGMA table_info("{name}")'):
                    base = 'int64' if 'INT' in typ.upper() else 'float64' if any(t in typ.upper() for t in ('REAL', 'FLOAT', 'DOUBLE')) else 'string'
                    nullable = not bool(notnull)  # SQLite non-INTEGER PK may accept NULL.
                    if pk and typ.upper() == 'INTEGER':
                        nullable = False
                    table['columns'].append({'column': col, 'go_field': go_name(col), 'go_type': ('*' if nullable else '') + base, 'nullable': nullable, 'primary_key': bool(pk), 'default': default})
                tables.append(table)
                known.add(name)
    return tables


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    tables = extract(args.source.resolve())
    target = root / 'services/api-server/internal/model'
    target.mkdir(parents=True, exist_ok=True)
    for table in tables:
        lines = ['// Code generated by scripts/entities/import_legacy.py; DO NOT EDIT.', '// Source: ' + table['source'] + ':' + str(table['line']), '', 'package model', '']
        if any('time.Time' in c['go_type'] for c in table['columns']):
            lines += ['import "time"', '']
        lines += ['// ' + table['entity'] + ' maps the legacy ' + table['table'] + ' table.', 'type ' + table['entity'] + ' struct {']
        for c in table['columns']:
            lines.append('\t' + c['go_field'] + ' ' + c['go_type'] + ' `db:"' + c['column'] + '" json:"-"`')
        lines += ['}', '', '// TableName returns the legacy SQLite table name.', 'func (' + table['entity'] + ') TableName() string {', '\treturn "' + table['table'] + '"', '}', '']
        (target / (table['table'] + '.go')).write_text('\n'.join(lines), encoding='utf-8')
    report = root / 'json/entities/legacy-schema.json'
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(json.dumps(tables, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Generated {len(tables)} entities, {sum(len(t["columns"]) for t in tables)} columns')


if __name__ == '__main__':
    main()
