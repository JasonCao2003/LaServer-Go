"""Extract literal public protocol constants and route names, never execute legacy code."""
import ast
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
source = root.parent / 'LaServer/services/game-api/business/account'
lines = ['// Code generated by scripts/entities/import_contracts.py; DO NOT EDIT.', 'package service', '']
routes = json.loads((root / 'json/api/legacy-routes.json').read_text())
lines += ['var LegacyPaths = []string{'] + [json.dumps(r['path']) + ',' for r in routes] + ['}', '']
for file, variable in [('create/create.py', 'createResources'), ('login/login.py','loginResources'), ('auth_create/auth_create.py','authCreateResources'), ('auth_login/auth_login.py','authLoginResources')]:
    tree = ast.parse((source / file).read_text(encoding='utf-8-sig'))
    resources = next(ast.literal_eval(v) for n in ast.walk(tree) if isinstance(n, ast.Dict) for k,v in zip(n.keys,n.values) if isinstance(k,ast.Constant) and k.value=='resource_list')
    lines += ['var ' + variable + ' = []string{'] + [json.dumps(s) + ',' for s in resources] + ['}', '']
tree = ast.parse((source / 'sync_user_data/sync_user_data.py').read_text(encoding='utf-8-sig'))
default = next(ast.literal_eval(n.value) for n in ast.walk(tree) if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='DEFAULT_USERDATA_B64' for t in n.targets))
lines += ['const defaultUserdata = ' + json.dumps(default), '']
definitions = json.loads((source.parent.parent / 'config/checkpoint_defs.json').read_text(encoding='utf-8-sig'))
orders = {}
for item in definitions:
    orders.setdefault(str(item['level_id']), item['arc_order'])
lines += ['var checkpointOrders = map[string]int64{'] + [json.dumps(k) + ':' + str(v) + ',' for k,v in orders.items()] + ['}', '']
tree = ast.parse((source / 'get_vars/get_vars.py').read_text(encoding='utf-8-sig'))
variables = next(ast.literal_eval(n.value) for n in ast.walk(tree) if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='response_body' for t in n.targets))
lines += ['const variablesJSON = ' + json.dumps(json.dumps(variables, ensure_ascii=False)), '']
(root / 'services/api-server/internal/service/legacy_contracts.go').write_text('\n'.join(lines), encoding='utf-8')
